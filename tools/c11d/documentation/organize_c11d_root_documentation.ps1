[CmdletBinding()]
param(
    [Parameter()][string]$Root = '',
    [Parameter()][switch]$PreflightOnly,
    [Parameter()][switch]$Apply
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 2.0
if ($PreflightOnly -and $Apply) { throw 'SELECT_ONLY_ONE_OF_PreflightOnly_OR_Apply' }
if (-not $PreflightOnly -and -not $Apply) { $PreflightOnly = $true }
if ([string]::IsNullOrWhiteSpace($Root)) {
    $Root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..\..'))
}
$Root = (Resolve-Path -LiteralPath $Root).Path.TrimEnd([char[]]@('\','/'))
if (-not (Test-Path -LiteralPath (Join-Path $Root 'AGENTS.md') -PathType Leaf)) { throw ('NOT_C11D_REPOSITORY_ROOT=' + $Root) }
$Encoding = New-Object System.Text.UTF8Encoding($false)
$GeneratorPath = 'tools/c11d/documentation/organize_c11d_root_documentation.ps1'
$ExpectedPins = @(
    [pscustomobject]@{path='AGENTS.md';sha256='0d4565e57b9fe9bba88a88f10babd175f3bb5e3fb437014866ed1e67d3016b37'},
    [pscustomobject]@{path='.continue/rules/CONTINUE.md';sha256='52776e55023a36e1ead71cf39a93337ca96f6097bd2c88018c3353484145ac86'},
    [pscustomobject]@{path='release/C11C_FREEZE_PACKAGE_MANIFEST.json';sha256='e405d08e4d166b1ad95953558f4a088e73eea9527e6e89244beb4096eac4b953';bytes=796318}
)
$MapMd = Join-Path $Root 'docs\current\d\C11D_ROOT_DOCUMENTATION_MIGRATION_MAP_GENERATED.md'
$MapJson = Join-Path $Root 'docs\current\d\C11D_ROOT_DOCUMENTATION_MIGRATION_MAP_GENERATED.json'

function Get-Sha256Lower([string]$Path) { return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant() }
function Get-Rel([string]$Path) { return $Path.Substring($Root.Length + 1).Replace('\','/') }
function Assert-GeneratedMapOutputs {
    if (Test-Path -LiteralPath $MapMd -PathType Leaf) {
        $lines = [IO.File]::ReadAllLines($MapMd)
        if ($lines.Count -eq 0 -or $lines[0] -ne '<!-- GENERATED BY tools/c11d/documentation/organize_c11d_root_documentation.ps1; DO NOT EDIT -->') {
            throw ('OUTPUT_CONFLICT_NOT_GENERATED=' + (Get-Rel $MapMd))
        }
    } elseif (Test-Path -LiteralPath $MapMd) { throw ('OUTPUT_NOT_FILE=' + (Get-Rel $MapMd)) }
    if (Test-Path -LiteralPath $MapJson -PathType Leaf) {
        $old = Get-Content -LiteralPath $MapJson -Raw -Encoding UTF8 | ConvertFrom-Json
        if ([string]$old.schema -ne 'C11D-ROOT-DOCUMENTATION-MIGRATION-MAP-V1' -or [string]$old.generator -ne $GeneratorPath) {
            throw ('OUTPUT_CONFLICT_NOT_GENERATED=' + (Get-Rel $MapJson))
        }
    } elseif (Test-Path -LiteralPath $MapJson) { throw ('OUTPUT_NOT_FILE=' + (Get-Rel $MapJson)) }
}
function Get-Destination([string]$Name) {
    if ($Name -in @('C11D_CONTEXT_SNAPSHOT_MANIFEST.json','C11D_CONTEXT_SNAPSHOT_README.md')) {
        return ('docs/history/d/snapshots/20261029_193950/' + $Name)
    }
    if ($Name -eq 'D9.10_QT_GUI_RUNTIME_ACCEPTANCE_CHECKPOINT.md') { return 'docs/history/d/root-documentation/acceptance/' + $Name }
    if ($Name -eq 'MASTER_HANDOVER_C11D_D9.10_QT_GUI_RUNTIME_20261009.md' -or $Name -eq 'START_PROMPT_C11D_D9.10_QT_GUI_RUNTIME_20261009.md') {
        return 'docs/history/d/root-documentation/legacy-d9_10/' + $Name
    }
    if ($Name -match '^README_C11D_CHALLENGE_') { return 'docs/history/d/root-documentation/challenge/' + $Name }
    if ($Name -match '^README_C11D_RENDERER_') { return 'docs/history/d/root-documentation/renderer/' + $Name }
    if ($Name -match '^README_C11D_VISUAL_LOOP_') { return 'docs/history/d/root-documentation/visual-loops/' + $Name }
    if ($Name -match '^README_C11D_VISUAL_DRILL_') { return 'docs/history/d/root-documentation/visual-drills/' + $Name }
    if ($Name -match '^README_C11D_V2B_') { return 'docs/history/d/root-documentation/v2b/' + $Name }
    if ($Name -match '^README_C11D_SHARED_') { return 'docs/history/d/root-documentation/shared-production-context/' + $Name }
    if ($Name -match '^README_C11D_UNIFIED_') { return 'docs/history/d/root-documentation/presentation-delivery/' + $Name }
    if ($Name -match '^README_C11D_D9') { return 'docs/history/d/root-documentation/acceptance/' + $Name }
    if ($Name -match '^README_C11D_D10') { return 'docs/history/d/root-documentation/d10/' + $Name }
    if ($Name -match '^README_C11D_(CHECKPOINT|CONTEXT|CONTINUITY|CURRENT_CONTEXT|NIGHTLY|PHASE_P|DOCUMENTATION)') { return 'docs/history/d/root-documentation/continuity/' + $Name }
    return 'docs/history/d/root-documentation/other/' + $Name
}

# Pins are checked before reading or moving any candidate.
foreach ($pin in $ExpectedPins) {
    $path = Join-Path $Root ($pin.path.Replace('/','\'))
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw ('CORE_PIN_MISSING=' + $pin.path) }
    $actual = Get-Sha256Lower $path
    if ($actual -ne $pin.sha256) { throw ('CORE_PIN_MISMATCH=' + $pin.path + '; expected=' + $pin.sha256 + '; actual=' + $actual) }
    $pinBytesProperty = $pin.PSObject.Properties['bytes']
    if ($null -ne $pinBytesProperty -and $null -ne $pinBytesProperty.Value -and [long](Get-Item -LiteralPath $path).Length -ne [long]$pinBytesProperty.Value) {
        throw ('CORE_PIN_SIZE_MISMATCH=' + $pin.path)
    }
    Write-Host ('VERIFIED_CORE_PIN=' + $pin.path + '=' + $actual)
}
$CManifestPath = Join-Path $Root 'release\C11C_FREEZE_PACKAGE_MANIFEST.json'
$CManifest = Get-Content -LiteralPath $CManifestPath -Raw -Encoding UTF8 | ConvertFrom-Json
$CManifestMap = @{}
foreach ($item in $CManifest.source_files) {
    if ($null -eq $item) { continue }
    $pathProperty = $item.PSObject.Properties['path']
    if ($null -eq $pathProperty -or [string]::IsNullOrWhiteSpace([string]$pathProperty.Value)) { continue }
    $manifestRel = [string]$pathProperty.Value
    $manifestRel = $manifestRel.Replace('\','/')
    $CManifestMap[$manifestRel] = $item
}

# Candidate list is intentionally narrow: root-level C11-D overlay readmes and stale snapshot/continuity documents.
$candidates = New-Object 'System.Collections.Generic.List[object]'
foreach ($file in (Get-ChildItem -LiteralPath $Root -File -Force | Sort-Object -Property Name)) {
    $isCandidate = $false
    if ($file.Name -like 'README_C11D_*.md') { $isCandidate = $true }
    if ($file.Name -in @('D9.10_QT_GUI_RUNTIME_ACCEPTANCE_CHECKPOINT.md','MASTER_HANDOVER_C11D_D9.10_QT_GUI_RUNTIME_20261009.md','START_PROMPT_C11D_D9.10_QT_GUI_RUNTIME_20261009.md','C11D_CONTEXT_SNAPSHOT_README.md','C11D_CONTEXT_SNAPSHOT_MANIFEST.json')) { $isCandidate = $true }
    if ($isCandidate) { $candidates.Add($file) }
}

# Build one bounded text scan for references. The previous snapshot's generated manifest and the live generated catalog are excluded,
# because they enumerate paths rather than expressing dependencies on those pathnames.
$textExtensions = @('.md','.txt','.rst','.adoc','.json','.yaml','.yml','.ps1','.py','.bat','.csv','.gd','.tscn','.godot')
$skipDirectoryNames = @('.git','.godot','.mono','.import','.vscode','.idea','__pycache__','.pytest_cache','.mypy_cache','.ruff_cache','.venv','venv','env','artifacts','node_modules','.cache','bin','obj','coverage')
$ignoreReferenceFiles = @(
    'C11D_CONTEXT_SNAPSHOT_MANIFEST.json',
    'C11D_DOCUMENTATION_CATALOG_GENERATED.md','C11D_DOCUMENTATION_CATALOG_GENERATED.json',
    'C11D_ROOT_DOCUMENTATION_MIGRATION_MAP_GENERATED.md','C11D_ROOT_DOCUMENTATION_MIGRATION_MAP_GENERATED.json',
    'C11D_ROOT_DOCUMENTATION_SNAPSHOT_AUDIT_20261029_V1.md',
    'organize_c11d_root_documentation.ps1','organize_c11d_documentation.ps1'
)
$candidateNames = @($candidates | ForEach-Object { $_.Name })
$references = @{}
foreach ($name in $candidateNames) { $references[$name] = New-Object 'System.Collections.Generic.List[string]' }
$textFiles = New-Object 'System.Collections.Generic.List[object]'
$stack = New-Object 'System.Collections.Generic.Stack[string]'
$stack.Push($Root)
while ($stack.Count -gt 0) {
    $dir = $stack.Pop()
    foreach ($entry in (Get-ChildItem -LiteralPath $dir -Force -ErrorAction Stop)) {
        if ($entry.PSIsContainer) {
            if (($entry.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) { continue }
            if ($skipDirectoryNames -contains $entry.Name.ToLowerInvariant()) { continue }
            if ($entry.FullName -match '(?i)[\\/]docs[\\/]history[\\/]root_conflicts(?:[\\/]|$)') { continue }
            $stack.Push($entry.FullName)
            continue
        }
        if (($entry.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) { continue }
        if ($ignoreReferenceFiles -contains $entry.Name) { continue }
        if ($entry.Length -gt 5MB) { continue }
        if ($textExtensions -notcontains $entry.Extension.ToLowerInvariant()) { continue }
        $textFiles.Add([pscustomobject]@{full_path=$entry.FullName;relative= (Get-Rel $entry.FullName)})
    }
}
foreach ($source in $textFiles) {
    $content = [IO.File]::ReadAllText([string]$source.full_path)
    foreach ($name in $candidateNames) {
        if ($source.relative -ceq $name) { continue }
        # The snapshot metadata files are generated archive members, not source inputs to the packager; their embedded names are not a dependency.
        if ($name -in @('C11D_CONTEXT_SNAPSHOT_README.md','C11D_CONTEXT_SNAPSHOT_MANIFEST.json')) { continue }
        if ($content.IndexOf([string]$name,[StringComparison]::OrdinalIgnoreCase) -ge 0) {
            $references[$name].Add([string]$source.relative)
        }
    }
}

Assert-GeneratedMapOutputs
$plan = New-Object 'System.Collections.Generic.List[object]'
foreach ($file in $candidates) {
    $name = [string]$file.Name
    $sourceRel = $name
    $sourcePath = $file.FullName
    $bytes = [long]$file.Length
    $hash = Get-Sha256Lower $sourcePath
    $destRel = Get-Destination $name
    $refList = @($references[$name].ToArray() | Select-Object -Unique | Sort-Object)
    $action = 'WOULD_MOVE'
    $reason = 'Root-level historical D documentation; categorized archive destination is defined.'
    if ($CManifestMap.ContainsKey($sourceRel)) {
        $manifestItem = $CManifestMap[$sourceRel]
        $manifestHashProperty = $manifestItem.PSObject.Properties['sha256']
        $manifestBytesProperty = $manifestItem.PSObject.Properties['bytes']
        if ($null -eq $manifestHashProperty -or $null -eq $manifestBytesProperty -or [string]$manifestHashProperty.Value -ne $hash -or [long]$manifestBytesProperty.Value -ne $bytes) {
            throw ('FROZEN_C_ENTRY_MISMATCH_FOR_ROOT_DOC=' + $sourceRel)
        }
        $action = 'RETAIN_C11C_FREEZE_MANIFEST_PATH'
        $reason = 'Canonical C11-C manifest explicitly includes this root path; moving it would break frozen-baseline path integrity.'
        $destRel = $sourceRel
    } elseif ($refList.Count -gt 0 -and $name -notin @('C11D_CONTEXT_SNAPSHOT_README.md','C11D_CONTEXT_SNAPSHOT_MANIFEST.json')) {
        $action = 'RETAIN_REFERENCED_ROOT_PATH'
        $reason = 'One or more source documents/manifests still name this root file; relocation requires a separately reconciled reference migration.'
        $destRel = $sourceRel
    } else {
        $destPath = Join-Path $Root ($destRel.Replace('/','\'))
        if (Test-Path -LiteralPath $destPath -PathType Leaf) {
            $destHash = Get-Sha256Lower $destPath
            if ($destHash -eq $hash -and [long](Get-Item -LiteralPath $destPath).Length -eq $bytes) {
                $action = 'WOULD_DEDUPLICATE_IDENTICAL_DESTINATION'
                $reason = 'Destination already contains identical bytes; source removal is permitted only after exact SHA-256/size match.'
            } else {
                $action = 'CONFLICT_DESTINATION_DIFFERS'
                $reason = 'Destination exists with different bytes; no automatic overwrite or rename is allowed.'
            }
        }
    }
    $plan.Add([pscustomobject]@{source=$sourceRel;destination=$destRel;bytes=$bytes;sha256=$hash;action=$action;reason=$reason;references=$refList})
}

# Root-level overlay manifests are package metadata, not ordinary current documentation. Keep them byte-for-byte where historical manifests expect them.
foreach ($file in (Get-ChildItem -LiteralPath $Root -File -Force -Filter 'C11D_*_OVERLAY_MANIFEST*.json' | Sort-Object -Property Name)) {
    if (@($plan | Where-Object { $_.source -ceq $file.Name }).Count -eq 0) {
        $plan.Add([pscustomobject]@{source=$file.Name;destination=$file.Name;bytes=[long]$file.Length;sha256=(Get-Sha256Lower $file.FullName);action='RETAIN_ROOT_OVERLAY_MANIFEST';reason='Historical package-relative manifest metadata retained byte-for-byte at its original root path.';references=@()})
    }
}

# Validate previous migration outputs and keep successful historical moves in the generated map on repeat runs.
$merged = @{}
if (Test-Path -LiteralPath $MapJson -PathType Leaf) {
    $previous = Get-Content -LiteralPath $MapJson -Raw -Encoding UTF8 | ConvertFrom-Json
    foreach ($old in $previous.entries) {
        $oldSource = [string]$old.source
        if ([string]$old.action -eq 'MOVED' -or [string]$old.action -eq 'DEDUPLICATED_IDENTICAL') {
            $oldDestPath = Join-Path $Root ([string]$old.destination.Replace('/','\'))
            if (-not (Test-Path -LiteralPath $oldDestPath -PathType Leaf) -or (Get-Sha256Lower $oldDestPath) -ne [string]$old.sha256) {
                throw ('PREVIOUSLY_MIGRATED_DOCUMENT_DRIFT=' + $oldSource + ' -> ' + [string]$old.destination)
            }
        }
        $merged[$oldSource] = $old
    }
}
foreach ($entry in $plan) { $merged[[string]$entry.source] = $entry }
$conflicts = @($plan | Where-Object { $_.action -eq 'CONFLICT_DESTINATION_DIFFERS' })
$moves = @($plan | Where-Object { $_.action -eq 'WOULD_MOVE' })
$dedupe = @($plan | Where-Object { $_.action -eq 'WOULD_DEDUPLICATE_IDENTICAL_DESTINATION' })
$retained = @($plan | Where-Object { $_.action -like 'RETAIN_*' })

Write-Host ('ROOT_DOCUMENTATION_ORGANIZER=' + $GeneratorPath)
Write-Host ('ACTIVE_CHECKOUT=' + $Root)
Write-Host ('ROOT_DOC_CANDIDATES=' + $candidates.Count)
Write-Host ('PLANNED_MOVES=' + $moves.Count)
Write-Host ('IDENTICAL_DESTINATIONS=' + $dedupe.Count)
Write-Host ('RETAINED_PROTECTED_OR_REFERENCED=' + $retained.Count)
Write-Host ('DESTINATION_CONFLICTS=' + $conflicts.Count)
foreach ($item in $plan) {
    Write-Host ('ROOT_DOC=' + $item.action + '|' + $item.source + '|' + $item.destination + '|' + $item.sha256)
}
if ($conflicts.Count -gt 0) { throw ('ROOT_DOCUMENTATION_MIGRATION_BLOCKED_CONFLICTS=' + $conflicts.Count) }
if ($PreflightOnly) {
    Write-Host 'C11D_ROOT_DOCUMENTATION_PREFLIGHT=PASS_NO_FILES_WRITTEN'
    Write-Host ('PLANNED_MAP=' + $MapMd)
    Write-Host ('PLANNED_MAP=' + $MapJson)
    exit 0
}

# No write begins until the complete plan, destination collisions, source pins and pre-existing map are validated.
foreach ($entry in $plan) {
    if ($entry.action -eq 'WOULD_MOVE') {
        $sourcePath = Join-Path $Root ([string]$entry.source)
        $destPath = Join-Path $Root ([string]$entry.destination.Replace('/','\'))
        if (-not (Test-Path -LiteralPath $sourcePath -PathType Leaf)) { throw ('MOVE_SOURCE_DISAPPEARED=' + $entry.source) }
        if (Test-Path -LiteralPath $destPath) { throw ('MOVE_DESTINATION_APPEARED=' + $entry.destination) }
    }
    if ($entry.action -eq 'WOULD_DEDUPLICATE_IDENTICAL_DESTINATION') {
        $sourcePath = Join-Path $Root ([string]$entry.source)
        $destPath = Join-Path $Root ([string]$entry.destination.Replace('/','\'))
        if ((Get-Sha256Lower $sourcePath) -ne [string]$entry.sha256 -or (Get-Sha256Lower $destPath) -ne [string]$entry.sha256) { throw ('DEDUPLICATION_HASH_DRIFT=' + $entry.source) }
    }
}
foreach ($entry in $plan) {
    if ($entry.action -eq 'WOULD_MOVE') {
        $sourcePath = Join-Path $Root ([string]$entry.source)
        $destPath = Join-Path $Root ([string]$entry.destination.Replace('/','\'))
        New-Item -ItemType Directory -Path (Split-Path -Parent $destPath) -Force | Out-Null
        Move-Item -LiteralPath $sourcePath -Destination $destPath
        if ((Get-Sha256Lower $destPath) -ne [string]$entry.sha256 -or (Test-Path -LiteralPath $sourcePath)) { throw ('POST_MOVE_HASH_OR_SOURCE_FAIL=' + $entry.source) }
        $entry.action = 'MOVED'
        $entry.reason = 'Moved without content modification; SHA-256 verified at destination.'
    } elseif ($entry.action -eq 'WOULD_DEDUPLICATE_IDENTICAL_DESTINATION') {
        $sourcePath = Join-Path $Root ([string]$entry.source)
        Remove-Item -LiteralPath $sourcePath -Force
        $entry.action = 'DEDUPLICATED_IDENTICAL'
        $entry.reason = 'Verified identical destination retained; duplicate root copy removed.'
    }
}

# Rebuild the merged history after applying outcomes.
foreach ($entry in $plan) { $merged[[string]$entry.source] = $entry }
$allEntries = @($merged.Values | Sort-Object -Property source)
$gitCommit = $null
try {
    $git = Get-Command git -ErrorAction SilentlyContinue
    if ($null -ne $git) {
        $value = & $git.Source -C $Root rev-parse HEAD 2>$null
        if ($LASTEXITCODE -eq 0 -and $value) { $gitCommit = ([string]$value).Trim() }
    }
} catch { }
$data = [ordered]@{
    schema='C11D-ROOT-DOCUMENTATION-MIGRATION-MAP-V1'
    generator=$GeneratorPath
    generated_at_utc=[DateTime]::UtcNow.ToString('o')
    source_root=$Root
    git_commit=$gitCommit
    source_pins=$ExpectedPins
    candidate_count=$candidates.Count
    moved_count=@($allEntries | Where-Object { $_.action -eq 'MOVED' }).Count
    deduplicated_identical_count=@($allEntries | Where-Object { $_.action -eq 'DEDUPLICATED_IDENTICAL' }).Count
    retained_count=@($allEntries | Where-Object { ([string]$_.action).StartsWith('RETAIN_') }).Count
    entries=$allEntries
    policy=@('AGENTS.md and README.md remain canonical root entrypoints','all canonical C11-C manifest-listed paths remain unchanged','documents with outstanding references remain at their old paths','moved files are byte-preserved and SHA-256 verified','root overlay manifests remain at historical root paths','no source documentation content is rewritten')
}
$jsonText = ($data | ConvertTo-Json -Depth 12) + "`n"
$md = New-Object 'System.Collections.Generic.List[string]'
$md.Add('<!-- GENERATED BY tools/c11d/documentation/organize_c11d_root_documentation.ps1; DO NOT EDIT -->')
$md.Add('# C11-D — Mapa generado de reorganización documental de raíz')
$md.Add('')
$md.Add(('Generado UTC: ' + [DateTime]::UtcNow.ToString('o')))
$md.Add(('Checkout: `' + $Root + '`'))
if ($null -ne $gitCommit) { $md.Add(('Git commit: `' + $gitCommit + '`')) }
$md.Add(('Documentos de raíz candidatos observados: **' + $candidates.Count + '**'))
$md.Add(('Movidos acumulados: **' + $data.moved_count + '**; duplicados idénticos deduplicados: **' + $data.deduplicated_identical_count + '**; retenidos por protección/referencia: **' + $data.retained_count + '**.'))
$md.Add('')
$md.Add('La acción `MOVED` significa que el archivo original se trasladó sin modificar sus bytes y que su SHA-256 coincide en el destino. Las acciones `RETAIN_*` son excepciones intencionadas, no fallos de organización.')
$md.Add('')
$md.Add('| Acción | Ruta de origen | Ruta de destino | Bytes | SHA-256 | Motivo |')
$md.Add('|---|---|---|---:|---|---|')
foreach ($entry in $allEntries) {
    $reason = ([string]$entry.reason).Replace('|','\|').Replace("`r",' ').Replace("`n",' ')
    $md.Add(('| `' + $entry.action + '` | `' + $entry.source + '` | `' + $entry.destination + '` | ' + [string]$entry.bytes + ' | `' + [string]$entry.sha256 + '` | ' + $reason + ' |'))
}
$md.Add('')
$md.Add('## Límites')
$md.Add('')
$md.Add('- No se modifican `AGENTS.md`, `.continue/rules/CONTINUE.md` ni `release/C11C_FREEZE_PACKAGE_MANIFEST.json`.')
$md.Add('- Los dos documentos de raíz que estén listados en el manifiesto C11-C quedan en su ubicación canónica.')
$md.Add('- Los documentos aún referenciados por fuentes/manifiestos existentes se conservan en raíz hasta reconciliar esas referencias en una migración distinta.')
$md.Add('- No se cambian el contenido de los documentos trasladados ni las rutas dentro de manifiestos históricos.')
$mdText = ($md -join "`n") + "`n"

$mdTemp = $MapMd + '.' + [guid]::NewGuid().ToString('N') + '.tmp'
$jsonTemp = $MapJson + '.' + [guid]::NewGuid().ToString('N') + '.tmp'
try {
    [IO.File]::WriteAllText($mdTemp,$mdText,$Encoding)
    [IO.File]::WriteAllText($jsonTemp,$jsonText,$Encoding)
    Move-Item -LiteralPath $mdTemp -Destination $MapMd -Force
    Move-Item -LiteralPath $jsonTemp -Destination $MapJson -Force
} finally {
    foreach ($tmp in @($mdTemp,$jsonTemp)) { if (Test-Path -LiteralPath $tmp -PathType Leaf) { Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue } }
}

# Final integrity: canonical C manifest and pins are still unchanged, and every moved document remains byte-identical.
foreach ($pin in $ExpectedPins) {
    $path = Join-Path $Root ($pin.path.Replace('/','\'))
    if ((Get-Sha256Lower $path) -ne $pin.sha256) { throw ('POST_MIGRATION_PIN_FAIL=' + $pin.path) }
}
foreach ($entry in $allEntries) {
    if ([string]$entry.action -eq 'MOVED' -or [string]$entry.action -eq 'DEDUPLICATED_IDENTICAL') {
        $destPath = Join-Path $Root ([string]$entry.destination.Replace('/','\'))
        if (-not (Test-Path -LiteralPath $destPath -PathType Leaf) -or (Get-Sha256Lower $destPath) -ne [string]$entry.sha256) { throw ('POST_MIGRATION_TARGET_FAIL=' + [string]$entry.destination) }
    }
}
Write-Host ('MIGRATION_MAP_MARKDOWN=' + $MapMd)
Write-Host ('MIGRATION_MAP_JSON=' + $MapJson)
Write-Host ('MIGRATION_MAP_JSON_SHA256=' + (Get-Sha256Lower $MapJson))
Write-Host ('MIGRATION_MAP_MARKDOWN_SHA256=' + (Get-Sha256Lower $MapMd))
Write-Host ('MOVED_TOTAL=' + $data.moved_count)
Write-Host ('RETAINED_TOTAL=' + $data.retained_count)
Write-Host 'C11C_FROZEN_MANIFEST=PASS_UNCHANGED'
Write-Host 'C11D_ROOT_DOCUMENTATION_ORGANIZATION=PASS_HASH_PRESERVING_MIGRATION'
