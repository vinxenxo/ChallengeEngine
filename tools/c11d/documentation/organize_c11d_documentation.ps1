[CmdletBinding()]
param(
    [string]$Root = '',
    [switch]$PreflightOnly
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

if ([string]::IsNullOrWhiteSpace($Root)) {
    $Root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..\..\..'))
}
$Root = (Resolve-Path -LiteralPath $Root).Path
if (-not (Test-Path -LiteralPath (Join-Path $Root 'AGENTS.md') -PathType Leaf)) { throw ('NOT_C11D_REPOSITORY_ROOT=' + $Root) }
$CatalogMd = Join-Path $Root 'docs\current\d\C11D_DOCUMENTATION_CATALOG_GENERATED.md'
$CatalogJson = Join-Path $Root 'docs\current\d\C11D_DOCUMENTATION_CATALOG_GENERATED.json'
$GeneratorPath = 'tools/c11d/documentation/organize_c11d_documentation.ps1'
$Encoding = New-Object System.Text.UTF8Encoding($false)

function Get-Sha256Lower([string]$Path) {
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant()
}
function Get-Rel([string]$FullPath) {
    return $FullPath.Substring($Root.Length + 1).Replace('\','/')
}
function Get-Title([string]$Path) {
    try {
        $lines = Get-Content -LiteralPath $Path -Encoding UTF8 -TotalCount 40 -ErrorAction Stop
        foreach ($line in $lines) {
            if ([string]$line -match '^\s*#\s+(.+?)\s*$') { return $Matches[1].Trim() }
        }
    } catch { }
    return [IO.Path]::GetFileNameWithoutExtension($Path)
}
function Get-Category([string]$RelativePath) {
    $name = [IO.Path]::GetFileName($RelativePath)
    if ($RelativePath -match '^docs/history/') { return '90_HISTORY_AND_SUPERSEDED_CONTEXT' }
    if ($name -match '^(C11D_ENGINEERING_PHASE_LEDGER|C11D_FULL_CONTEXT_CONTINUITY_CHECKPOINT|C11D_DOCUMENTATION_INDEX_AND_ARCHIVE_POLICY|C11D_DOCUMENTATION_CATALOG|C11-D_ROADMAP|C11-D_MILESTONES|C11D_PROJECT_CONTEXT|C11D_FULL_CONTEXT_HANDOVER|C11D_CURRENT_EVIDENCE_INDEX)') { return '00_CONTINUITY_AND_NAVIGATION' }
    if ($name -match '(RENDER|PAYLOAD|EDITORIAL|COMPOSI|BINDING|BINDER|PRESENTATION|TIMEBASE|TIMELINE|TEMPORAL|FRAME_PROGRAM|MUSIC|AUDIO|MUX|VISUAL_LOOP|VISUAL_DRILL|SEED_DOMAIN|CANDIDATE_IO|CANDIDATE_IDENTITY)') { return '10_RENDER_AND_PRODUCTION_PATH' }
    if ($name -match '(PHASE_[A-Z]+|AUTHORITY|DECISION|ADJUDIC|DISPOSITION|POLICY|GATE|CLOSEOUT|APPROVAL|FREEZE_ELIGIBILITY)') { return '20_GOVERNANCE_AND_DECISIONS' }
    if ($name -match '(ACCEPTANCE|EVIDENCE|RECEIPT|RESULT|REPORT|AUDIT|VERIFICATION|TEST|RUNTIME|QA|CHECKPOINT)') { return '30_ACCEPTANCE_AND_EVIDENCE' }
    if ($name -match '(OVERLAY|MANIFEST|ARCHIVE|PACKAG|SNAPSHOT|MIGRATION|REPAIR|ROOT_ORGANIZATION)') { return '40_PACKAGING_AND_OPERATIONS' }
    return '50_OTHER_D_REFERENCE'
}
function Get-Lineage([string]$RelativePath, [string]$Name) {
    if ($RelativePath -match '^docs/history/') { return 'HISTORICAL_PATH_KEEP_FOR_TRACEABILITY' }
    if ($RelativePath -match 'C11D_ENGINEERING_PHASE_LEDGER_20261029_V18|C11D_FULL_CONTEXT_CONTINUITY_CHECKPOINT_20261029_V41|C11D_PHASE_AD_EXECUTION_CLOSEOUT_20261029_V1|C11D_PHASE_AD_EXECUTION_EVIDENCE_RECEIPT_20261029_V1|C11D_PHASE_AD_OPERATOR_AUTHORITY_DECISION_GATE_20261029_V1') { return 'CURRENT_GOVERNANCE_REFERENCE_VERIFY_PIN' }
    if ($Name -match '_V\d+(?:\.|_|\.)|_20\d{6}') { return 'VERSIONED_REFERENCE_NOT_AUTO_SUPERSEDED' }
    return 'REFERENCE_REVIEW_AUTHORITY_FROM_CONTENT_AND_PINS'
}
function Get-Link([string]$RelativePath) {
    if ($RelativePath -match '^docs/current/d/') { $path = './' + $RelativePath.Substring('docs/current/d/'.Length) }
    elseif ($RelativePath -match '^docs/history/d/') { $path = '../../history/d/' + $RelativePath.Substring('docs/history/d/'.Length) }
    elseif ($RelativePath -match '^docs/history/c11d/') { $path = '../../history/c11d/' + $RelativePath.Substring('docs/history/c11d/'.Length) }
    elseif ($RelativePath -match '^docs/history/master-prompts/c11d/') { $path = '../../history/master-prompts/c11d/' + $RelativePath.Substring('docs/history/master-prompts/c11d/'.Length) }
    elseif ($RelativePath -match '^prompts/') { $path = '../../../' + $RelativePath }
    elseif ($RelativePath -match '^docs/master-prompts/') { $path = '../../master-prompts/' + $RelativePath.Substring('docs/master-prompts/'.Length) }
    else { $path = $RelativePath }
    $parts = $path.Split('/') | ForEach-Object { [Uri]::EscapeDataString([string]$_) }
    return ($parts -join '/')
}
function Test-GeneratedOutput([string]$Path, [string]$Kind) {
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return }
    if ($Kind -eq 'Markdown') {
        $first = [IO.File]::ReadAllLines($Path)[0]
        if ($first -ne '<!-- GENERATED BY tools/c11d/documentation/organize_c11d_documentation.ps1; DO NOT EDIT -->') {
            throw ('OUTPUT_CONFLICT_NOT_GENERATED=' + $Path)
        }
    } else {
        $existing = Get-Content -LiteralPath $Path -Raw -Encoding UTF8 | ConvertFrom-Json
        if ([string]$existing.generator -ne $GeneratorPath -or [string]$existing.schema -ne 'C11D-LIVE-DOCUMENTATION-CATALOG-V1') {
            throw ('OUTPUT_CONFLICT_NOT_GENERATED=' + $Path)
        }
    }
}

# The three canonical pins are hard blockers; contextual pins are recorded for review.
$corePins = @(
    [pscustomobject]@{path='AGENTS.md'; expected='0d4565e57b9fe9bba88a88f10babd175f3bb5e3fb437014866ed1e67d3016b37'; bytes=$null},
    [pscustomobject]@{path='.continue/rules/CONTINUE.md'; expected='52776e55023a36e1ead71cf39a93337ca96f6097bd2c88018c3353484145ac86'; bytes=$null},
    [pscustomobject]@{path='release/C11C_FREEZE_PACKAGE_MANIFEST.json'; expected='e405d08e4d166b1ad95953558f4a088e73eea9527e6e89244beb4096eac4b953'; bytes=796318}
)
$pinResults = New-Object 'System.Collections.Generic.List[object]'
foreach ($pin in $corePins) {
    $path = Join-Path $Root ($pin.path.Replace('/','\'))
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw ('CORE_PIN_MISSING=' + $pin.path) }
    $actual = Get-Sha256Lower $path
    $length = [long](Get-Item -LiteralPath $path).Length
    if ($actual -ne $pin.expected) { throw ('CORE_PIN_MISMATCH=' + $pin.path + '; expected=' + $pin.expected + '; actual=' + $actual) }
    if ($null -ne $pin.bytes -and $length -ne [long]$pin.bytes) { throw ('CORE_PIN_SIZE_MISMATCH=' + $pin.path + '; bytes=' + $length) }
    $pinResults.Add([pscustomobject]@{path=$pin.path;expected_sha256=$pin.expected;actual_sha256=$actual;bytes=$length;status='PASS'})
}
$contextPins = @(
    [pscustomobject]@{path='docs/current/d/C11D_ENGINEERING_PHASE_LEDGER_20261029_V18.md';expected='7731b98a79ca3b0cbe42256866bb8c1093389c40d5fe502bbfba7ac038b2ea90'},
    [pscustomobject]@{path='docs/current/d/C11D_FULL_CONTEXT_CONTINUITY_CHECKPOINT_20261029_V41.md';expected='2d2f165872e76f40afa86fbf774500c1a97c5cec3c193e26c9cc46c39f2f5ff4'},
    [pscustomobject]@{path='docs/current/d/C11D_PHASE_AD_EXECUTION_CLOSEOUT_20261029_V1.md';expected='22ed115bb58f9a9c84bb4942cd86af1f6d5a7bd2b72c3981037f209768ee4652'},
    [pscustomobject]@{path='docs/current/d/C11D_PHASE_AD_EXECUTION_EVIDENCE_RECEIPT_20261029_V1.json';expected='800cf33d7e53af989d05d5b8096d11e2909d1c486a6ebc469f025b0ea5bb94f3'},
    [pscustomobject]@{path='docs/current/d/C11D_PHASE_AD_OPERATOR_AUTHORITY_DECISION_GATE_20261029_V1.json';expected='63339254dd444c38a932b8b582bc0af600d309786f46d1e8dd2b92dbf07054e5'}
)
foreach ($pin in $contextPins) {
    $path = Join-Path $Root ($pin.path.Replace('/','\'))
    if (Test-Path -LiteralPath $path -PathType Leaf) {
        $actual = Get-Sha256Lower $path
        $status = if ($actual -eq $pin.expected) { 'PASS' } else { 'CHANGED_REVIEW_ACTIVE_CHECKOUT' }
        $pinResults.Add([pscustomobject]@{path=$pin.path;expected_sha256=$pin.expected;actual_sha256=$actual;bytes=[long](Get-Item -LiteralPath $path).Length;status=$status})
    } else {
        $pinResults.Add([pscustomobject]@{path=$pin.path;expected_sha256=$pin.expected;actual_sha256=$null;bytes=$null;status='MISSING_REVIEW_ACTIVE_CHECKOUT'})
    }
}

$scanRoots = @(
    [pscustomobject]@{path='docs/current/d'; filter='ALL_D_DOCS'},
    [pscustomobject]@{path='docs/history/d'; filter='ALL_D_ROOT_HISTORY'},
    [pscustomobject]@{path='docs/history/c11d'; filter='ALL_D_HISTORY'},
    [pscustomobject]@{path='docs/history/master-prompts/c11d'; filter='ALL_D_HISTORY_PROMPTS'},
    [pscustomobject]@{path='prompts'; filter='C11D_NAMED_PROMPTS'},
    [pscustomobject]@{path='docs/master-prompts'; filter='C11D_NAMED_MASTER_PROMPTS'},
    [pscustomobject]@{path='.'; filter='ROOT_D_METADATA'}
)
$allowedExtensions = @('.md','.json','.txt','.csv','.ps1','.bat','.yml','.yaml','.toml')
$itemsByPath = @{}
foreach ($scan in $scanRoots) {
    $absolute = Join-Path $Root ($scan.path.Replace('/','\'))
    if (-not (Test-Path -LiteralPath $absolute -PathType Container)) { continue }
    if ($scan.filter -eq 'ROOT_D_METADATA') {
        $sourceFiles = Get-ChildItem -LiteralPath $absolute -File -Force -ErrorAction Stop
    } else {
        $sourceFiles = Get-ChildItem -LiteralPath $absolute -Recurse -File -Force -ErrorAction Stop
    }
    foreach ($file in $sourceFiles) {
        $ext = $file.Extension.ToLowerInvariant()
        if ($allowedExtensions -notcontains $ext) { continue }
        if ($scan.filter -eq 'ROOT_D_METADATA' -and $file.Name -notmatch '^(README_C11D_.*\.md|D9\.10_QT_GUI_RUNTIME_ACCEPTANCE_CHECKPOINT\.md|MASTER_HANDOVER_C11D_D9\.10_QT_GUI_RUNTIME_20261009\.md|START_PROMPT_C11D_D9\.10_QT_GUI_RUNTIME_20261009\.md|C11D_CONTEXT_SNAPSHOT_README\.md|C11D_CONTEXT_SNAPSHOT_MANIFEST\.json|C11D_.*OVERLAY_MANIFEST.*\.json)$') { continue }
        $relative = Get-Rel $file.FullName
        if ($relative -eq 'docs/current/d/C11D_DOCUMENTATION_CATALOG_GENERATED.md' -or $relative -eq 'docs/current/d/C11D_DOCUMENTATION_CATALOG_GENERATED.json') { continue }
        if ($scan.filter -like 'C11D_NAMED_*' -and $file.Name -notmatch '(?i)C11D|C11-D') { continue }
        if ($itemsByPath.ContainsKey($relative)) { continue }
        $title = Get-Title $file.FullName
        $itemsByPath[$relative] = [pscustomobject]@{
            path=$relative; name=$file.Name; title=$title; category=(Get-Category $relative); lineage=(Get-Lineage $relative $file.Name)
            bytes=[long]$file.Length; sha256=(Get-Sha256Lower $file.FullName); link=(Get-Link $relative)
        }
    }
}
$items = @($itemsByPath.Values | Sort-Object -Property category,path)
$categoryCounts = @($items | Group-Object -Property category | Sort-Object -Property Name | ForEach-Object { [pscustomobject]@{category=$_.Name;count=$_.Count} })
$lineageCounts = @($items | Group-Object -Property lineage | Sort-Object -Property Name | ForEach-Object { [pscustomobject]@{lineage=$_.Name;count=$_.Count} })

Test-GeneratedOutput -Path $CatalogMd -Kind 'Markdown'
Test-GeneratedOutput -Path $CatalogJson -Kind 'Json'
$gitCommit = $null
try {
    $gitCmd = Get-Command git -ErrorAction SilentlyContinue
    if ($null -ne $gitCmd) {
        $gitOutput = & $gitCmd.Source -C $Root rev-parse HEAD 2>$null
        if ($LASTEXITCODE -eq 0 -and $gitOutput) { $gitCommit = ([string]$gitOutput).Trim() }
    }
} catch { }

Write-Host ('DOCUMENTATION_ORGANIZER=' + $GeneratorPath)
Write-Host ('ACTIVE_CHECKOUT=' + $Root)
Write-Host ('DOC_ITEMS_CATALOGUED=' + $items.Count)
foreach ($row in $categoryCounts) { Write-Host ('DOC_CATEGORY=' + $row.category + ':' + $row.count) }
foreach ($pin in $pinResults) { Write-Host ('DOC_PIN=' + $pin.path + ':' + $pin.status + ':' + [string]$pin.actual_sha256) }
Write-Host 'SOURCE_FILES_MOVED=0'
Write-Host 'SOURCE_FILES_RENAMED=0'
Write-Host 'SOURCE_FILES_DELETED=0'
if ($PreflightOnly) {
    Write-Host 'C11D_DOCUMENTATION_CATALOG_PREFLIGHT=PASS_NO_FILES_WRITTEN'
    Write-Host ('PLANNED_OUTPUT=' + $CatalogMd)
    Write-Host ('PLANNED_OUTPUT=' + $CatalogJson)
    exit 0
}

$catalogData = [ordered]@{
    schema='C11D-LIVE-DOCUMENTATION-CATALOG-V1'
    generator=$GeneratorPath
    generated_at_utc=[DateTime]::UtcNow.ToString('o')
    source_root=$Root
    git_commit=$gitCommit
    entry_count=$items.Count
    source_pins=$pinResults.ToArray()
    category_counts=$categoryCounts
    lineage_counts=$lineageCounts
    files=$items
    policy=@('catalogue only; no source-document moves or renames','historical/versioned filenames do not automatically establish supersession','core pin mismatch blocks catalog generation')
}
$jsonText = ($catalogData | ConvertTo-Json -Depth 12) + "`n"
$md = New-Object 'System.Collections.Generic.List[string]'
$md.Add('<!-- GENERATED BY tools/c11d/documentation/organize_c11d_documentation.ps1; DO NOT EDIT -->')
$md.Add('# C11-D — Catálogo documental vivo')
$md.Add('')
$md.Add(('Generado UTC: ' + [DateTime]::UtcNow.ToString('o')))
$md.Add(('Checkout: `' + $Root + '`'))
if ($null -ne $gitCommit) { $md.Add(('Git commit: `' + $gitCommit + '`')) }
$md.Add(('Documentos catalogados: **' + $items.Count + '**'))
$md.Add('')
$md.Add('> Este archivo es navegación generada. No establece autoridad ni declara supersesión automática. El script no mueve, renombra ni borra fuentes.')
$md.Add('')
$md.Add('## Pins')
$md.Add('')
$md.Add('| Fuente | Estado | SHA-256 observado | Bytes |')
$md.Add('|---|---|---|---:|')
foreach ($pin in $pinResults) { $md.Add(('| `' + $pin.path + '` | `' + $pin.status + '` | `' + [string]$pin.actual_sha256 + '` | ' + [string]$pin.bytes + ' |')) }
$md.Add('')
$md.Add('## Conteos por categoría')
$md.Add('')
foreach ($row in $categoryCounts) { $md.Add(('- **' + $row.category + ':** ' + $row.count)) }
$md.Add('')
foreach ($category in ($categoryCounts | ForEach-Object { $_.category })) {
    $md.Add(('## ' + $category))
    $md.Add('')
    $md.Add('| Documento | Linaje | Bytes | SHA-256 |')
    $md.Add('|---|---|---:|---|')
    foreach ($item in ($items | Where-Object { $_.category -eq $category })) {
        $label = ([string]$item.title).Replace('|','\|').Replace("`r",' ').Replace("`n",' ')
        $md.Add(('| [' + $label + '](' + $item.link + ') (`' + $item.name + '`) | `' + $item.lineage + '` | ' + $item.bytes + ' | `' + $item.sha256 + '` |'))
    }
    $md.Add('')
}
$md.Add('## Regla de archivo')
$md.Add('')
$md.Add('No muevas ni elimines fuentes a partir de este catálogo. Para una reorganización física futura se requiere un mapa completo de referencias, un plan revisable, recibos de hash y reconciliación de cualquier contrato/manifiesto que dependa de esas rutas.')
$mdText = ($md -join "`n") + "`n"

$mdTemp = $CatalogMd + '.' + [guid]::NewGuid().ToString('N') + '.tmp'
$jsonTemp = $CatalogJson + '.' + [guid]::NewGuid().ToString('N') + '.tmp'
try {
    [IO.File]::WriteAllText($mdTemp,$mdText,$Encoding)
    [IO.File]::WriteAllText($jsonTemp,$jsonText,$Encoding)
    Move-Item -LiteralPath $mdTemp -Destination $CatalogMd -Force
    Move-Item -LiteralPath $jsonTemp -Destination $CatalogJson -Force
} finally {
    foreach ($tmp in @($mdTemp,$jsonTemp)) { if (Test-Path -LiteralPath $tmp -PathType Leaf) { Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue } }
}
Write-Host ('CATALOG_MARKDOWN=' + $CatalogMd)
Write-Host ('CATALOG_JSON=' + $CatalogJson)
Write-Host ('CATALOG_MARKDOWN_SHA256=' + (Get-Sha256Lower $CatalogMd))
Write-Host ('CATALOG_JSON_SHA256=' + (Get-Sha256Lower $CatalogJson))
Write-Host 'C11D_DOCUMENTATION_CATALOG=PASS_CATALOG_ONLY_NO_SOURCE_MOVES'
