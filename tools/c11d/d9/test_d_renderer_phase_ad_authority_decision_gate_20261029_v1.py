#!/usr/bin/env python3
"""Contract tests for Phase AD operator authority decision gate."""
from __future__ import annotations
import argparse, json, sys, unittest
from pathlib import Path

class PhaseADTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        ap=argparse.ArgumentParser()
        ap.add_argument('--phase-ac-result-json', required=True)
        ap.add_argument('--phase-ad-packet-json', required=True)
        args=ap.parse_args()
        cls.ac=json.loads(Path(args.phase_ac_result_json).read_text(encoding='utf-8'))
        cls.ad=json.loads(Path(args.phase_ad_packet_json).read_text(encoding='utf-8'))
        cls.rows=cls.ad['decisions']
        cls.ids=[r['decision_id'] for r in cls.rows]
    def test_01_ac_phase(self): self.assertEqual(self.ac['phase'],'AC')
    def test_02_ac_review_complete(self): self.assertEqual(self.ac['status'],'PASS_CONTENT_REVIEW_COMPLETE_NO_APPLICABLE_D_RENDER_AUTHORITY_FOUND')
    def test_03_bundle_sha(self): self.assertEqual(self.ac['input']['source_bundle_sha256'],'5ee6ec0f5a6b3a0884c22bbecfc98691269bd431adc896c088e7eb7f9d0b7f08')
    def test_04_source_count(self): self.assertEqual(self.ac['counts']['remaining_candidates_reviewed_in_phase_ac'],57)
    def test_05_medium_count(self): self.assertEqual(self.ac['counts']['medium_priority'],55)
    def test_06_low_count(self): self.assertEqual(self.ac['counts']['low_priority'],2)
    def test_07_all_hashes_match(self): self.assertEqual(self.ac['counts']['source_hash_matches'],57)
    def test_08_no_hash_mismatch(self): self.assertEqual(self.ac['counts']['source_hash_mismatches'],0)
    def test_09_no_sources_missing(self): self.assertEqual(self.ac['counts']['source_files_missing'],0)
    def test_10_no_applicable_render_authority(self): self.assertEqual(self.ac['counts']['authority_records_applicable_to_first_d_baseline_render'],0)
    def test_11_no_policy_adoption(self): self.assertEqual(self.ac['counts']['policy_adoptions'],0)
    def test_12_no_operator_adjudication(self): self.assertEqual(self.ac['counts']['authority_adjudications_from_operator_evidence'],0)
    def test_13_scoped_claim_only(self): self.assertTrue(self.ac['coverage']['no_global_absence_claim'])
    def test_14_d914_out_of_scope(self): self.assertEqual(self.ac['counts']['bounded_qualification_records_out_of_scope'],1)
    def test_15_semantic_limited(self): self.assertIn('NOT_GRANTED',self.ac['authority_conclusion']['semantic_binding_authority'])
    def test_16_projection_not_granted(self): self.assertEqual(self.ac['authority_conclusion']['renderer_projection_authority'],'NOT_GRANTED')
    def test_17_renderer_not_granted(self): self.assertEqual(self.ac['authority_conclusion']['renderer_activation_authority'],'NOT_GRANTED')
    def test_18_payload_not_granted(self): self.assertEqual(self.ac['authority_conclusion']['payload_materialization_authority'],'NOT_GRANTED')
    def test_19_media_not_granted(self): self.assertEqual(self.ac['authority_conclusion']['media_creation_authority'],'NOT_GRANTED')
    def test_20_renderer_off(self): self.assertEqual(self.ac['governance']['renderer'],'OFF')
    def test_21_no_media(self): self.assertFalse(self.ac['governance']['media_created'])
    def test_22_no_payload(self): self.assertFalse(self.ac['governance']['payload_materialized'])
    def test_23_input_inadmissible(self): self.assertFalse(self.ac['governance']['candidate_input_admissible'])
    def test_24_seed_domains_incomplete(self): self.assertFalse(self.ac['governance']['seed_domains_complete_for_candidate_input'])
    def test_25_master_seed_not_adopted(self): self.assertEqual(self.ac['governance']['master_seed'],'NOT_ADOPTED')
    def test_26_binding_count_zero(self): self.assertEqual(self.ac['governance']['approved_bindings'],0)
    def test_27_projection_count_zero(self): self.assertEqual(self.ac['governance']['approved_renderer_projection_bindings'],0)
    def test_28_d917_no_go(self): self.assertEqual(self.ac['governance']['D9.17'],'BLOCKED_NO_GO')
    def test_29_d10_blocked(self): self.assertEqual(self.ac['governance']['D10'],'BLOCKED_FOR_PROMOTION')
    def test_30_release_none(self): self.assertEqual(self.ac['governance']['release_authority'],'NONE')
    def test_31_ad_status_pending(self): self.assertEqual(self.ad['status'],'PENDING_OPERATOR_CHOICE_NO_APPLICABLE_AUTHORITY_SUBMITTED')
    def test_32_ad_phase(self): self.assertEqual(self.ad['phase'],'AD')
    def test_33_exact_nine_ids(self): self.assertEqual(self.ids,['R-01-TIMEBASE-SAMPLING','R-02-SPATIAL-MAPPING','R-03-PILOT-SCALAR-X-AND-PRESENTATION-Y','R-04-VISIBILITY-AND-REGION-OWNERSHIP','R-05-ASSET-GEOMETRY-ANCHOR-CROP-ROUNDING','R-06-INVALID-DATA-AND-TRACK-INTEGRITY','R-07-SEMANTIC-VISUAL-OWNERSHIP','R-08-CHALLENGE-008','R-09-CHALLENGE-009'])
    def test_34_nine_rows(self): self.assertEqual(len(self.rows),9)
    def test_35_all_rows_pending(self): self.assertTrue(all(r['operator_decision_gate_status']=='PENDING_OPERATOR_ACTION' for r in self.rows))
    def test_36_no_row_selected(self): self.assertTrue(all(r['selected_option'] is None for r in self.rows))
    def test_37_no_authority_hash_invented(self): self.assertTrue(all(r['authority_evidence_record_sha256'] is None for r in self.rows))
    def test_38_no_immutable_location_invented(self): self.assertTrue(all(r['authority_evidence_immutable_uri_or_path'] is None for r in self.rows))
    def test_39_exact_allowed_options(self): self.assertEqual(self.ad['operator_action_options'],['SUBMIT_REAL_IMMUTABLE_AUTHORITY_EVIDENCE','KEEP_BLOCKED_NO_POLICY_ADOPTION'])
    def test_40_operator_choice_pending(self): self.assertEqual(self.ad['operator_decision']['state'],'NOT_PROVIDED')
    def test_41_no_global_option_selected(self): self.assertIsNone(self.ad['operator_decision']['chosen_global_option'])
    def test_42_adjudication_pending(self): self.assertEqual(self.ad['authority_adjudication'],'PENDING_OPERATOR_ACTION')
    def test_43_policy_none(self): self.assertEqual(self.ad['policy_adoption'],'NONE')
    def test_44_evidence_count_zero(self): self.assertEqual(self.ad['authority_records_submitted'],0)
    def test_45_decisions_adjudicated_zero(self): self.assertEqual(self.ad['operator_decisions_adjudicated'],0)
    def test_46_required_fields_ten(self): self.assertEqual(len(self.ad['required_fields']),10)
    def test_47_each_row_fields(self): self.assertTrue(all(len(r['required_fields_checklist'])==10 for r in self.rows))
    def test_48_r08_timing_conflict(self): self.assertIn('11 seconds',self.rows[7]['timing_conflict_guard']); self.assertIn('12 seconds',self.rows[7]['timing_conflict_guard'])
    def test_49_r09_timing_conflict(self): self.assertIn('11 seconds',self.rows[8]['timing_conflict_guard']); self.assertIn('12 seconds',self.rows[8]['timing_conflict_guard'])
    def test_50_d48_blocked(self): self.assertEqual(self.ad['governance']['D4.8'],'BLOCKED')
    def test_51_d914_blocked(self): self.assertEqual(self.ad['governance']['D9.14'],'BLOCKED')
    def test_52_d916_blocked(self): self.assertEqual(self.ad['governance']['D9.16'],'BLOCKED')
    def test_53_d910_prepare_only(self): self.assertEqual(self.ad['governance']['D9.10'],'PREPARE_ONLY')
    def test_54_baseline_approval_missing(self): self.assertEqual(self.ad['governance']['baseline_approval'],'MISSING')
    def test_55_freeze_ineligible(self): self.assertFalse(self.ad['governance']['freeze_eligible'])
    def test_56_c11c_manifest_pin(self): self.assertEqual(self.ad['governance']['c11c_manifest_sha256'],'e405d08e4d166b1ad95953558f4a088e73eea9527e6e89244beb4096eac4b953')
    def test_57_first_render_blocked(self): self.assertEqual(self.ad['first_render_readiness'],'BLOCKED')
    def test_58_next_action(self): self.assertTrue(self.ad['next_action'].startswith('OPERATOR_SUBMIT_REAL_IMMUTABLE_AUTHORITY_EVIDENCE'))
    def test_59_no_policy_adoption_in_global_locks(self): self.assertEqual(self.ad['policy_adoption'],'NONE')
    def test_60_no_runtime_authorization_claim(self): self.assertIn('No operator decision',self.ad['warning'])

if __name__=='__main__':
    suite=unittest.defaultTestLoader.loadTestsFromTestCase(PhaseADTests)
    result=unittest.TextTestRunner(verbosity=2).run(suite)
    print(f'PHASE_AD_AUTHORITY_DECISION_GATE_TESTS={result.testsRun}/{result.testsRun}')
    sys.exit(0 if result.wasSuccessful() else 1)
